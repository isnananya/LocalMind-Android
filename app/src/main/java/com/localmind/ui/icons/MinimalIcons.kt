package com.localmind.ui.icons

// ============================================================================
// MinimalIcons.kt — the ONLY Compose Material icons this app uses.
//
// WHY THIS FILE EXISTS (APK size)
//   `androidx.compose.material:material-icons-extended` is a 34 MB AAR holding
//   ~2 000 ImageVector definitions per style across 5 styles. This app draws 50
//   of them. Depending on that artifact drags the whole set into the build;
//   inlining just those vectors lets the dependency be dropped. There are 51
//   entries below because Send is needed plain *and* AutoMirrored.
//
// WHERE THE DATA CAME FROM (do not "fix" the numbers)
//   Byte-exact copies of the ImageVector.Builder bodies taken from
//     * material-icons-extended-android:1.7.2 — 35 of the filled icons
//     * material-icons-core-android:1.7.2     — the 13 icons that live in the
//       core set (Add, ArrowBack, Check, Close, Delete, Favorite, Info, Person,
//       PlayArrow, Refresh, Search, Send, Share) plus all 3 AutoMirrored ones.
//   Every float round-trips exactly. Nothing was rounded or simplified: a single
//   wrong coordinate makes the icon visibly wrong.
//
// HOW TO REGENERATE (after a Compose upgrade, or when adding an icon)
//   1. Grab the AAR from the Gradle cache, e.g.
//        ~/.gradle/caches/modules-2/files-2.1/androidx.compose.material/
//          material-icons-extended-android/<ver>/<hash>/material-icons-extended-release.aar
//   2. Unzip it and take classes.jar (an .aar is a plain zip; `tar -xf x.aar` works).
//   3. The class for an icon is
//        androidx/compose/material/icons/filled/<Name>Kt.class
//      Icons in the *core* set are in material-icons-core-android instead, and the
//      AutoMirrored ones under
//        androidx/compose/material/icons/automirrored/filled/<Name>Kt.class
//   4. Read it back with
//        javap -p -c -cp classes.jar androidx.compose.material.icons.filled.<Name>Kt
//      `ImageVector.Builder(...)` gives name/defaultWidth/defaultHeight/
//      viewportWidth/viewportHeight/autoMirror; each `PathBuilder.<op>` call in
//      `_<name>` maps 1:1 onto the `path { }` DSL below (moveTo, horizontalLineTo,
//      horizontalLineToRelative, curveTo, close, ...).
//      Safer than transcribing by hand: put the AAR's classes.jar plus
//      compose ui/ui-graphics/ui-unit on a classpath, call the `get<Name>` getter by
//      reflection, then walk ImageVector.root and print each VectorPath and
//      PathNode — that is exactly how this file was produced.
//   5. Keep AutoMirrored icons in AppIconsAutoMirrored and pass `autoMirror = true`
//      to ImageVector.Builder — in Compose 1.7.x that constructor parameter is
//      spelled `autoMirror` (singular), NOT `autoMirrored`.
//
// `by lazy` matters: each vector is built on first draw, not at class-init time.
// ============================================================================

